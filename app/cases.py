def get_case_by_id(case_id: str) -> dict[str, Any] | None:
    """Return case dict by id, or None if not found."""
    return next((c for c in CASES if c["id"] == case_id), None)


def get_random_case() -> dict[str, Any]:
    """Return a random case dictionary from the list."""
    return random.choice(CASES)

